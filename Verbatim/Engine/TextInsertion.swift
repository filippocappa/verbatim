import AppKit
import ApplicationServices

/// The text field the user is typing in, read through the Accessibility API.
struct FocusedField {
    let element: AXUIElement
    let value: String?
    let selection: CFRange?
    let isSecure: Bool

    static func current() -> FocusedField? {
        let system = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(system, 0.25)
        var focused: CFTypeRef?
        var err = AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focused)

        // Chromium/Electron apps (Slack, VS Code, Cursor, Notion...) hide their text tree until asked.
        if err != .success, let app = NSWorkspace.shared.frontmostApplication {
            let axApp = AXUIElementCreateApplication(app.processIdentifier)
            AXUIElementSetAttributeValue(axApp, "AXManualAccessibility" as CFString, kCFBooleanTrue)
            err = AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focused)
        }
        guard err == .success, let focused, CFGetTypeID(focused) == AXUIElementGetTypeID() else { return nil }
        let el = focused as! AXUIElement
        AXUIElementSetMessagingTimeout(el, 0.25)
        return FocusedField(element: el, value: readValue(el), selection: readSelection(el), isSecure: readRole(el) == "AXSecureTextField")
    }

    static func readValue(_ el: AXUIElement) -> String? {
        var v: CFTypeRef?
        guard AXUIElementCopyAttributeValue(el, kAXValueAttribute as CFString, &v) == .success else { return nil }
        return v as? String
    }

    static func readSelection(_ el: AXUIElement) -> CFRange? {
        var v: CFTypeRef?
        guard AXUIElementCopyAttributeValue(el, kAXSelectedTextRangeAttribute as CFString, &v) == .success,
              let v, CFGetTypeID(v) == AXValueGetTypeID() else { return nil }
        var range = CFRange()
        return AXValueGetValue(v as! AXValue, .cfRange, &range) ? range : nil
    }

    private static func readRole(_ el: AXUIElement) -> String? {
        var v: CFTypeRef?
        AXUIElementCopyAttributeValue(el, kAXRoleAttribute as CFString, &v)
        return v as? String
    }

    /// The character right before the cursor, if the app exposes it.
    var characterBeforeCursor: Character? {
        guard let value, let sel = selection, sel.location > 0 else { return nil }
        let ns = value as NSString
        guard sel.location <= ns.length else { return nil }
        let r = ns.rangeOfComposedCharacterSequence(at: sel.location - 1)
        return ns.substring(with: r).first
    }
}

enum Paster {
    /// Copies text to the clipboard the normal way (for Copy buttons in the app).
    static func copy(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    /// Puts the text on the clipboard and presses ⌘V. Unless `keep` is set, the user's old
    /// clipboard comes back a moment later and clipboard managers are told to skip the entry.
    static func paste(_ text: String, keep: Bool = false) {
        let pb = NSPasteboard.general
        let saved: [NSPasteboardItem] = (pb.pasteboardItems ?? []).compactMap { item in
            let copy = NSPasteboardItem()
            var any = false
            for type in item.types {
                if let data = item.data(forType: type) { copy.setData(data, forType: type); any = true }
            }
            return any ? copy : nil
        }

        pb.clearContents()
        pb.setString(text, forType: .string)
        if !keep {
        // Tells clipboard managers (Raycast, Maccy...) not to save this entry.
        pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        }
        let ourChange = pb.changeCount

        let src = CGEventSource(stateID: .combinedSessionState)
        let vKey: CGKeyCode = 9
        let down = CGEvent(keyboardEventSource: src, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: vKey, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)

        guard !keep else { return }
        Task { @MainActor in
            try? await Task.sleep(for: .milliseconds(800))
            guard pb.changeCount == ourChange else { return } // user copied something new meanwhile
            pb.clearContents()
            if !saved.isEmpty { pb.writeObjects(saved) }
        }
    }
}
